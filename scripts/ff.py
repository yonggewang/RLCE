"""Minimal linear algebra over GF(p), p prime. Self-contained, numpy-based."""
import numpy as np

class GF:
    def __init__(self, p):
        self.p = p
        # precompute inverses
        self.inv = np.zeros(p, dtype=np.int64)
        for a in range(1, p):
            self.inv[a] = pow(int(a), p - 2, p)

    def rref(self, M):
        """Reduced row echelon form over GF(p). Returns (R, pivots)."""
        p = self.p
        R = (np.array(M, dtype=np.int64) % p).copy()
        rows, cols = R.shape
        pivots = []
        r = 0
        for c in range(cols):
            if r >= rows:
                break
            # find pivot
            piv = -1
            for i in range(r, rows):
                if R[i, c] % p != 0:
                    piv = i
                    break
            if piv == -1:
                continue
            R[[r, piv]] = R[[piv, r]]
            R[r] = (R[r] * self.inv[R[r, c]]) % p
            for i in range(rows):
                if i != r and R[i, c] != 0:
                    R[i] = (R[i] - R[i, c] * R[r]) % p
            pivots.append(c)
            r += 1
        return R, pivots

    def rank(self, M):
        _, piv = self.rref(M)
        return len(piv)

    def rowspace_basis(self, M):
        """Basis (rows) of the row space."""
        R, piv = self.rref(M)
        return R[:len(piv)]

    def nullspace(self, M):
        """Basis of right null space: vectors x with M x = 0."""
        p = self.p
        R, piv = self.rref(M)
        rows, cols = R.shape
        pivset = set(piv)
        free = [c for c in range(cols) if c not in pivset]
        basis = []
        for f in free:
            x = np.zeros(cols, dtype=np.int64)
            x[f] = 1
            for i, pc in enumerate(piv):
                x[pc] = (-R[i, f]) % p
            basis.append(x)
        return np.array(basis, dtype=np.int64) if basis else np.zeros((0, cols), dtype=np.int64)

    def matmul(self, A, B):
        return (np.array(A, dtype=np.int64) @ np.array(B, dtype=np.int64)) % self.p

def schur_square_basis(gf, G):
    """Basis of the square code C*C where C = rowspace(G).
    Generated by componentwise products of all pairs of basis rows (incl. squares)."""
    G = np.array(G, dtype=np.int64) % gf.p
    k, n = G.shape
    prods = []
    for i in range(k):
        for j in range(i, k):
            prods.append((G[i] * G[j]) % gf.p)
    P = np.array(prods, dtype=np.int64)
    return gf.rowspace_basis(P)

def square_dim(gf, G):
    return schur_square_basis(gf, G).shape[0]
